
"""
AI Interviewer Agent.

Generates natural, professional interviewer responses
using Groq's OpenAI-compatible API.

Responsibilities:
- Maintain interview conversation context.
- Ask questions from the interview plan.
- Respond naturally to candidate answers.
- Handle repeat, skip, and clarification requests.
- Avoid repeating previously asked questions.
- Decide when the interview is complete.
"""

import json
import logging
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from config import settings
from agents.groq_client import get_groq_client


logger = logging.getLogger(__name__)


class InterviewerError(Exception):
    """Raised when the interviewer cannot generate a response."""


@dataclass
class InterviewerReply:
    """Structured response generated by the interviewer."""

    text: str
    action: str = "continue"
    question_id: str | None = None
    interview_complete: bool = False


class InterviewerAgent:

    VALID_ACTIONS = {
        "continue",
        "repeat",
        "skip",
        "clarify",
        "finish",
    }

    def __init__(
        self,
        client: Any | None = None,
        model: str | None = None,
    ):
        # Groq is the primary text-generation provider.
        self.model = model or settings.groq_text_model

        # Optional injected client keeps tests independent
        # of the actual Groq API.
        self.client = client
        self.last_first_token_seconds: float | None = None

        prompt_path = (
            Path(__file__).resolve().parent.parent
            / "prompts"
            / "interviewer_system.txt"
        )

        try:
            self.system_prompt = prompt_path.read_text(
                encoding="utf-8"
            )
        except OSError as exc:
            raise InterviewerError(
                f"Could not load interviewer prompt: {exc}"
            ) from exc

    def _get_client(self) -> Any:
        """Initialize the Groq client only when required."""

        if self.client is not None:
            return self.client
        try:
            return get_groq_client()
        except RuntimeError as exc:
            raise InterviewerError(str(exc)) from exc

    async def generate_response(
        self,
        candidate_message: str,
        interview_plan: dict[str, Any],
        conversation_history: list[dict[str, Any]],
        current_question: dict[str, Any] | None = None,
        interview_stage: str = "interview",
    ) -> InterviewerReply:
        """
        Generate the next interviewer response.
        """

        if not candidate_message.strip():
            raise ValueError(
                "Candidate message cannot be empty."
            )

        planned_questions = []
        for question in interview_plan.get("questions", []):
            if not isinstance(question, dict):
                continue
            planned_questions.append({
                "id": question.get("id"),
                "category": question.get("category"),
                "question": question.get("question"),
                "skills_tested": question.get("skills_tested", []),
            })

        planned_by_text = {
            str(question.get("question", "")).strip().casefold(): str(question.get("id"))
            for question in planned_questions
            if question.get("question")
        }
        planned_ids = {str(question.get("id")) for question in planned_questions}
        asked_question_ids: list[str] = []
        for turn in conversation_history:
            if not isinstance(turn, dict):
                continue
            metadata = turn.get("metadata") or {}
            question_id = metadata.get("question_id") if isinstance(metadata, dict) else None
            if question_id is None and turn.get("turn_type") == "question":
                question_id = planned_by_text.get(
                    str(turn.get("content", "")).strip().casefold()
                )
            if question_id is not None and str(question_id) in planned_ids:
                normalized_id = str(question_id)
                if normalized_id not in asked_question_ids:
                    asked_question_ids.append(normalized_id)

        recent_history = conversation_history[-7:]
        if (
            recent_history
            and recent_history[-1].get("role") in {"user", "candidate"}
            and recent_history[-1].get("content", "").strip() == candidate_message.strip()
        ):
            recent_history = recent_history[:-1]
        compact_history = [
            {
                "role": turn.get("role"),
                "type": turn.get("turn_type"),
                # Keep earlier context bounded; the current answer below stays
                # verbatim so the agent never silently changes candidate words.
                "content": str(turn.get("content", ""))[:360],
            }
            for turn in recent_history[-6:]
            if isinstance(turn, dict)
        ]

        compact_question = None
        if current_question:
            compact_question = {
                key: current_question.get(key)
                for key in ("id", "category", "question", "skills_tested")
                if key in current_question
            }

        context = {
            "stage": interview_stage,
            "questions": planned_questions,
            "asked_question_ids": asked_question_ids,
            "current_question": compact_question,
            "recent_turns": compact_history,
            "candidate_answer_verbatim": candidate_message,
        }

        instructions = self.system_prompt

        user_input = json.dumps(context, ensure_ascii=False, default=str)

        try:
            client = self._get_client()

            stream_started = time.perf_counter()
            self.last_first_token_seconds = None
            stream = await client.responses.create(
                model=self.model,
                instructions=instructions,
                input=user_input,
                text={
                    "format": {
                        "type": "json_object"
                    }
                },
                max_output_tokens=260,
                reasoning={"effort": "low"},
                stream=True,
            )

            response_parts: list[str] = []
            completed_response = None
            async for event in stream:
                event_type = getattr(event, "type", "")
                if event_type == "response.output_text.delta":
                    delta = getattr(event, "delta", "")
                    if delta:
                        if self.last_first_token_seconds is None:
                            self.last_first_token_seconds = (
                                time.perf_counter() - stream_started
                            )
                        response_parts.append(delta)
                elif event_type == "response.completed":
                    completed_response = getattr(event, "response", None)
                elif event_type in {"response.failed", "error"}:
                    raise InterviewerError("Groq response streaming failed.")

            response_text = "".join(response_parts)
            if not response_text and completed_response is not None:
                response_text = getattr(completed_response, "output_text", "")
            if self.last_first_token_seconds is not None:
                logger.info(
                    "Groq first text delta arrived in %.2fs.",
                    self.last_first_token_seconds,
                )

            if not response_text:
                raise InterviewerError(
                    "The AI returned an empty response."
                )

            return self._parse_response(response_text)

        except InterviewerError:
            raise

        except Exception as exc:
            raise InterviewerError(
                f"Failed to generate interviewer response: {exc}"
            ) from exc

    @classmethod
    def _parse_response(
        cls,
        response_text: str,
    ) -> InterviewerReply:
        """Validate and convert the model response."""

        try:
            data = json.loads(response_text)

            if not isinstance(data, dict):
                raise ValueError(
                    "Response must be a JSON object."
                )

            text = data.get("text")

            if not isinstance(text, str) or not text.strip():
                raise ValueError(
                    "Response text is missing."
                )

            action = data.get("action", "continue")

            if action not in cls.VALID_ACTIONS:
                action = "continue"

            question_id = data.get("question_id")

            if question_id is not None:
                question_id = str(question_id)

            interview_complete = (
                data.get("interview_complete", False) is True
            )

            return InterviewerReply(
                text=text.strip(),
                action=action,
                question_id=question_id,
                interview_complete=interview_complete,
            )

        except (json.JSONDecodeError, TypeError, ValueError) as exc:
            raise InterviewerError(
                f"Invalid interviewer response format: {exc}"
            ) from exc


# Shared interviewer instance.
# Safe to import without a configured Groq API key.
interviewer = InterviewerAgent()
